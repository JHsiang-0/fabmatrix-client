import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import test from 'node:test'

const connectionSource = await readFile(new URL('../src/views/ServerConnection.vue', import.meta.url), 'utf8')
const loginSource = await readFile(new URL('../src/views/Login.vue', import.meta.url), 'utf8')

test('服务器连接页保持单屏布局、可选 WebSocket 地址和四按钮操作区', () => {
  assert.match(connectionSource, /label="服务器 IP \/ 主机"/)
  assert.match(connectionSource, /label="端口"/)
  assert.match(connectionSource, /placeholder="28081"/)
  assert.match(connectionSource, /localhost:28081\/ws\/farm-status/)
  assert.match(connectionSource, />WebSocket 地址<\/span>/)
  assert.match(connectionSource, /initialWsEndpoint = parseWebSocketEndpoint\(initialConfig\.wsUrl\)/)
  assert.match(connectionSource, /initialAutoWsEndpoint = deriveWebSocketEndpoint\(initialEndpoint\)/)
  assert.match(connectionSource, /watch\(/)
  assert.match(connectionSource, /syncAutomaticWebSocketFields/)
  assert.match(connectionSource, /initialFormWsEndpoint = initialConfig\.wsUrl \? initialWsEndpoint : initialAutoWsEndpoint/)
  assert.match(connectionSource, /wsProtocol: initialFormWsEndpoint\.protocol/)
  assert.match(connectionSource, /wsAddress: initialFormWsEndpoint\.address/)
  assert.match(connectionSource, /customWsUrlEnabled: Boolean\(initialConfig\.wsUrl\)/)
  assert.match(connectionSource, /<t-switch[\s\S]*v-model="form\.customWsUrlEnabled"/)
  assert.match(connectionSource, /:disabled="!form\.customWsUrlEnabled"/)
  assert.match(connectionSource, /<t-option label="ws:\/\/" value="ws" \/>/)
  assert.match(connectionSource, /<t-option label="wss:\/\/" value="wss" \/>/)
  assert.match(connectionSource, /@click="testConnection"/)
  assert.match(connectionSource, /@click="saveAndConnect"/)
  assert.match(connectionSource, /保存并连接成功，尚未保存配置|服务器连接测试成功，尚未保存配置/)
  assert.match(connectionSource, /saveServerConfig\(\{ apiBaseUrl, wsUrl: form\.customWsUrlEnabled \? resolveWebSocketUrl\(\) : '' \}\)/)
  assert.match(connectionSource, /<t-typography-text disabled>嘉东三维管理平台<\/t-typography-text>/)
  assert.match(connectionSource, /<p class="connection-eyebrow">LOCAL EDITION<\/p>/)
  assert.match(connectionSource, /class="connection-current-config"/)
  assert.match(connectionSource, /class="connection-actions__right"/)
  assert.doesNotMatch(connectionSource, /connection-brand__mark|>3D<|安全连接配置/)
  assert.doesNotMatch(connectionSource, /扫描局域网|发现服务器|lanDiscovery/)
})

test('初始化入口通过正式状态接口原位切换并提供重试', () => {
  assert.match(loginSource, /getFirstAdminSetupStatus\(\)/)
  assert.match(loginSource, /if \(setupStatusPromise\) return setupStatusPromise/)
  assert.match(loginSource, /resolveSetupStatus\(\{ data: response\?\.data \}\)/)
  assert.match(loginSource, /const latestStatus = await loadSetupStatus\(\)/)
  assert.match(loginSource, /isSetupConflict\(error\)/)
  assert.match(loginSource, /@click="loadSetupStatus"/)
  assert.match(loginSource, /setupFirstAdmin\(\{[\s\S]*confirmPassword:/)
})
