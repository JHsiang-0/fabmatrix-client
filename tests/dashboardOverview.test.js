  assert.doesNotMatch(farmDashboardSource, /3F-一号车间|workshopName|dashboard-header__workshop-switch/)
  assert.match(farmDashboardSource, /<slot name="fullscreen-action"><\/slot>/)
  assert.equal((farmDashboardSource.match(/label: '打印机总数'/g) || []).length, 1)
  assert.equal((farmDashboardSource.match(/label: '正在打印'/g) || []).length, 1)
  assert.equal((farmDashboardSource.match(/label: '空闲打印机'/g) || []).length, 1)
  assert.equal((farmDashboardSource.match(/label: '异常设备'/g) || []).length, 1)
  assert.match(farmDashboardSource, /dashboardStatusCounts/)
  assert.match(farmDashboardSource, /store\.rawDeviceList/)
  assert.match(farmDashboardSource, /store\.realTimeStatus/)
  assert.match(farmDashboardSource, /normalizePrinterStatus/)
